"""
How each module type is laid out as a spreadsheet (sheets/<ModuleType>.ods, one workbook
per module type, every instance of that type in it), and the conversions both ways --
used by tools/export_sheets.py and tools/import_sheets.py (docs/DATA_MODEL.md).

Every workbook has a "Modules" sheet: one row per module instance (its id, name and every
single-valued field -- nested ones as dotted names like generation.budget). Each list in a
module is a sheet of its own, one row per item, its first column the module id; a list
inside a list item (a unit type's abilities, a location's units) is a sheet whose rows also
name that item. Row order is list order.

Columns marked "(info)" are for reading only -- a location's name next to its id, generated
data like adjacency -- and are ignored on import. Fields the sheets don't carry (a location's
boundary polygons, adjacency, label metrics: generated by the map tools) are kept from the
module as it stands.
"""
import copy
import json

INFO = ' (info)'


class Col:
    """One column: `header`, the item field `path` (a key, an int index for list items, or '.'
    for a list of bare values),
    `kind` ('str', 'int', 'num', 'bool', 'json', 'ids'), and whether it is `info` only.
    omit: on import, leave the field out when the cell is empty or holds `default` (the value an
    absent field means)."""

    def __init__(self, header, path=None, kind='str', info=False, omit=False, show=None, default=None):
        self.header = header + (INFO if info else '')
        self.path = header if path is None else path
        self.kind, self.info, self.omit, self.default = kind, info, omit, default
        self.show = show  # info columns: a function (item, doc, ctx) -> value


class Table:
    """A list in the module as a sheet. list_path: a dotted path to the list, or {tag: path}
    with `tag` a column naming which list a row belongs to. key: the item field matching rows to
    existing items (so fields the sheet lacks are kept). parent: (list path, key field, header,
    child field) for a list inside the items of another list. matrix: (child field, column key
    field, value field) -- one column per column key."""

    def __init__(self, sheet, list_path, cols, key=None, parent=None, tag=None, matrix=None):
        self.sheet, self.list_path, self.cols, self.key = sheet, list_path, cols, key
        self.parent, self.tag, self.matrix = parent, tag, matrix


def _loc_name(ctx, tid):
    return ctx['names'].get(tid)


